#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Launch the QD app under test on a throwaway SQLite DB, for E2E only.

This module writes **nothing** into the repository except the DB file it is
told to use (default `/tmp/qd-e2e-*.db`).  It never touches product code.

The app is started through `run.start_server()` in a child process.  A
`local_config` module is injected on `PYTHONPATH` so the run is fully
hermetic: no `local_config.py` is created inside the repo (that path is
gitignored anyway, but a stray file there would be residue we must not leave).

The same config values are also exported as environment variables so the
harness can *import* the app modules (config, db) in-process to inspect the
database, and see exactly the same settings the server saw.
"""

from __future__ import annotations

import json
import os
import shutil
import signal
import socket
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
VENV_PY = os.path.join(REPO, ".venv", "bin", "python")

# Fixed secrets so the parent process and the child process agree.
# AES_KEY must be a legal AES key length (16/24/32 bytes) or PyCryptodome
# raises `ValueError: Incorrect AES key length` on the first registration.
COOKIE_SIGN_SECRET = "e2e-cookie-sign-secret"
AES_KEY = "e2e-aes-key-16by"

# NOTE: `config.py` executes `from local_config import *` at line ~363, i.e.
# *while* the `config` module is still being imported.  `config.sqlite3.path`
# (a class attribute, line ~116) is therefore already defined and reachable
# through `sys.modules['config']`; we patch it here because it is NOT
# env-driven and `db/basedb.py` reads it at import time.
LOCAL_CONFIG_TEMPLATE = """\
# generated by tests/e2e/qd_runner.py -- do not edit
import sys as _sys

cookie_secret = bytes.fromhex(%(cookie_hex)r)
aes_key = bytes.fromhex(%(aes_hex)r)
_sys.modules["config"].sqlite3.path = %(db_path)r
"""


class AppError(RuntimeError):
    pass


def _port_is_free(port):
    """True if a server could bind `port` right now.

    `SO_REUSEADDR` mirrors what the real server does (tornado's
    `netutil.bind_sockets` sets it), and it is load-bearing: without it a
    previous run leaves the port in `TIME-WAIT` for ~60s, and the raw bind
    fails with EADDRINUSE even though nothing is listening.  That turned a
    legitimate immediate re-run into a bogus "port already in use" error.
    A *live* listener still fails the bind even with SO_REUSEADDR, so the
    guard keeps its teeth.
    """
    s = socket.socket()
    try:
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        s.bind(("127.0.0.1", port))
        return True
    except OSError:
        return False
    finally:
        s.close()


def free_port(preferred=None):
    """Return a usable TCP port on 127.0.0.1.

    `preferred=None`  -> pick an ephemeral port.
    `preferred=<int>` -> the caller pinned this port on purpose (e.g. it is the
        redirect URI registered with the IdP), so it MUST be honoured: if it is
        taken we raise instead of silently drifting to another port.  A silent
        fallback used to make the app listen on a port the Keycloak client
        `qd-e2e` does not know about, so the IdP kept calling the pinned port
        and the run died with a bare `ConnectionError` and **no** summary line
        -- which a loose CI grep can misread as a pass.
    """
    if preferred is None:
        s = socket.socket()
        s.bind(("127.0.0.1", 0))
        port = s.getsockname()[1]
        s.close()
        return port

    if not _port_is_free(preferred):
        raise AppError(
            f"port {preferred} is already in use on 127.0.0.1 and cannot fall "
            f"back to a random port: {preferred} is the redirect URI registered "
            f"with the Keycloak client, so the app must bind it (otherwise the "
            f"IdP calls {preferred} and the run dies with a ConnectionError "
            f"instead of printing a summary line). "
            f"Free port {preferred} and re-run."
        )
    return preferred


def _wait_http(url, timeout=60.0):
    deadline = time.time() + timeout
    last = None
    while time.time() < deadline:
        try:
            req = urllib.request.Request(url, method="GET")
            opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
            with opener.open(req, timeout=3) as resp:
                return resp.status
        except urllib.error.HTTPError as e:
            return e.code  # a real HTTP answer: the server is up
        except Exception as e:  # noqa: BLE001
            last = e
            time.sleep(0.3)
    raise AppError(f"server at {url} did not come up in {timeout}s: {last}")


class QdApp:
    """Context manager running the app under test."""

    def __init__(self, port=None, db_path=None, providers=None, domain=None,
                 extra_env=None, log_path=None):
        self.port = free_port(port)
        self.domain = domain or f"127.0.0.1:{self.port}"
        self.providers = providers or []
        self.db_path = db_path or os.path.join(
            tempfile.gettempdir(), f"qd-e2e-{os.getpid()}-{self.port}.db"
        )
        self.extra_env = dict(extra_env or {})
        self.log_path = log_path or os.path.join(
            tempfile.gettempdir(), f"qd-e2e-{self.port}.log"
        )
        self._tmpdir = None
        self.proc = None
        self.log = None

    # ---- lifecycle ----

    @property
    def base(self):
        return f"http://127.0.0.1:{self.port}"

    def _env(self):
        env = dict(os.environ)
        env.pop("http_proxy", None)
        env.pop("https_proxy", None)
        env.pop("HTTP_PROXY", None)
        env.pop("HTTPS_PROXY", None)
        env.update({
            "DB_TYPE": "sqlite3",
            "PORT": str(self.port),
            "BIND": "127.0.0.1",
            "DOMAIN": self.domain,
            "MULTI_PROCESS": "False",
            "AUTO_RELOAD": "False",
            "WORKER_METHOD": "Queue",
            "ACCESS_LOG": "False",
            "QD_DEBUG": "True",
            "DISPLAY_IMPORT_WARNING": "False",
            "COOKIE_SIGN_SECRET": COOKIE_SIGN_SECRET,
            "AES_KEY": AES_KEY,
            "OIDC_PROVIDERS": json.dumps(self.providers),
            # keep the task worker away from any real network
            "CHECK_TASK_LOOP": "60000",
            "PUSH_BATCH_SW": "False",
        })
        env.update(self.extra_env)
        return env

    def __enter__(self):
        # The DB file is what makes this hermetic; refuse to reuse a stale one.
        if os.path.exists(self.db_path):
            os.unlink(self.db_path)

        self._tmpdir = tempfile.mkdtemp(prefix="qd-e2e-localconfig-")
        self._write_local_config()

        env = self._env()
        env["PYTHONPATH"] = os.pathsep.join(
            [self._tmpdir, REPO, env.get("PYTHONPATH", "")]
        ).strip(os.pathsep)

        self.log = open(self.log_path, "wb")
        self.proc = subprocess.Popen(
            [VENV_PY, "-c",
             "import sys; sys.argv=['qd']; "
             "from run import start_server; start_server()"],
            cwd=REPO, env=env, stdout=self.log, stderr=subprocess.STDOUT,
            start_new_session=True,
        )
        try:
            _wait_http(self.base + "/login")
        except AppError:
            self.__exit__(None, None, None)
            raise AppError(
                f"app failed to start; log follows:\n{self.read_log()}"
            )
        return self

    def read_log(self):
        try:
            with open(self.log_path, "rb") as f:
                return f.read().decode("utf-8", "replace")[-8000:]
        except OSError:
            return "<no log>"

    def __exit__(self, *exc):
        if self.proc is not None:
            try:
                os.killpg(os.getpgid(self.proc.pid), signal.SIGTERM)
            except (ProcessLookupError, PermissionError):
                try:
                    self.proc.terminate()
                except ProcessLookupError:
                    pass
            try:
                self.proc.wait(timeout=15)
            except subprocess.TimeoutExpired:
                try:
                    os.killpg(os.getpgid(self.proc.pid), signal.SIGKILL)
                except (ProcessLookupError, PermissionError):
                    self.proc.kill()
                self.proc.wait(timeout=10)
            self.proc = None
        if self.log is not None:
            self.log.close()
            self.log = None
        if self._tmpdir and os.path.isdir(self._tmpdir):
            shutil.rmtree(self._tmpdir, ignore_errors=True)
            self._tmpdir = None
        return False

    # ---- in-process DB access (read-only assertions) ----

    def _write_local_config(self):
        """Write the injected `local_config` module (idempotent)."""
        with open(os.path.join(self._tmpdir, "local_config.py"), "w",
                  encoding="utf-8") as f:
            f.write(LOCAL_CONFIG_TEMPLATE % {
                "cookie_hex": COOKIE_SIGN_SECRET.encode().hex(),
                "aes_hex": AES_KEY.encode().hex(),
                "db_path": self.db_path,
            })

    @staticmethod
    def _install_env_for_import():
        """Make `import config` see the same settings the server saw."""
        os.environ["DB_TYPE"] = "sqlite3"
        os.environ["COOKIE_SIGN_SECRET"] = COOKIE_SIGN_SECRET
        os.environ["AES_KEY"] = AES_KEY

    def _import_db(self):
        self._install_env_for_import()
        if self._tmpdir not in sys.path:
            sys.path.insert(0, self._tmpdir)
        if REPO not in sys.path:
            sys.path.insert(0, REPO)
        # config.sqlite3.path is read at import time from the config package
        # dir; it is NOT env-driven, so it is patched by the injected
        # local_config module (see LOCAL_CONFIG_TEMPLATE).
        self._write_local_config()
        import db  # noqa: PLC0415
        return db

    def open_db(self):
        """Return a DB instance bound to this app's sqlite file."""
        db_mod = self._import_db()
        return db_mod.DB()

    def sqlite_rows(self, sql, params=()):
        """Raw sqlite read, independent of the ORM (evidence-grade)."""
        import sqlite3  # noqa: PLC0415
        con = sqlite3.connect(self.db_path)
        con.row_factory = sqlite3.Row
        try:
            return [dict(r) for r in con.execute(sql, params).fetchall()]
        finally:
            con.close()

    def sqlite_exec(self, sql, params=()):
        import sqlite3  # noqa: PLC0415
        con = sqlite3.connect(self.db_path)
        try:
            con.execute(sql, params)
            con.commit()
        finally:
            con.close()
